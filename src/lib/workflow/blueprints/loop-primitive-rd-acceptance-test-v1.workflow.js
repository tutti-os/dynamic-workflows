export const meta = {
  name: "RD Acceptance Delivery",
  description: "RD 工程师与独立 Reviewer 在有限轮次内迭代交付；Reviewer 只依据原始需求和仓库当前实现验收，不读取 RD 的交付说明。验收 PASS 后基于当前改动提交 MR/PR，未通过则输出现状报告。",
  requiresCwd: true,
};

export const inputs = {
  requirement: {
    type: "string",
    required: true,
    label: "原始需求",
    description: "RD 与 Reviewer 共享的唯一需求说明；它们仍会独立读取仓库和各自的运行时指令，但 Reviewer 不接收 RD 的交付叙述。请包含：1) 背景与目标；2) 改动范围（涉及模块/文件，已知即可）；3) 验收标准（逐条、可验证）；4) 明确不做的事项与约束。",
    placeholder: "背景与目标：\n\n改动范围：\n\n验收标准：\n1. \n2. \n\n明确不做：\n",
    widget: "textarea",
  },
};

phase("RD 交付与验收");

const delivery_loop = loop({
  id: "delivery_loop",
  label: "RD 交付循环",
  cwd: ".",
  maxIterations: 3,
  onMaxIterations: "complete",
  steps: [
    agent({
      id: "rd",
      label: "RD 工程师",
      session: { mode: "inherit", key: "rd_room" },
      prompt: `
启动工作目录：
{{workflow.cwd}}

原始需求：
{{requirement}}

你是负责端到端交付的 RD 工程师。请在上述 cwd 对应的项目目录中实现原始需求。交付物是可工作的代码改动，不是方案或计划文档。

工作方式：
1. 先检查相关代码、约定和已有实现，优先复用仓库现有模式；覆盖完成需求所涉及的调用面，不只修复表面症状。
2. 对不影响核心范围、可以安全回退的小缺口采用保守且合理的默认值继续完成，并在交付摘要中说明。只有当缺失信息会实质改变需求范围、造成不可逆后果或使验收标准无法成立时，才停止并标注「需要对齐」。
3. 保留用户当前工作区中的其他改动，不要回退或覆盖与本任务无关的内容。
4. 改动保留在工作区，不要自行 commit 或 push；提交由后续步骤统一处理。
5. 实现后运行与改动相关的 focused checks；检查失败或无法运行时如实说明，不要声称通过。

最后输出交付摘要，供后续修订和最终状态报告使用：
- 改动文件：逐个列出，每个一句话说明
- 实现说明：关键实现点、取舍与采用的默认值
- 已运行的检查及结果：
- 验证方式：如何确认原始需求被满足
`,
      appendPrompt: `
第 {{iteration}} 轮修订。

上一轮验收反馈：
{{acceptance}}

请继续在同一个项目目录中工作。先独立核对反馈与原始需求及实际代码是否一致，再修复其中标注为"阻断"的问题；"建议"项可顺手处理但不强制。Reviewer 不能扩展或改写原始需求：若反馈需要新增产品决策或明显超出原始范围，标注「需要对齐」并说明原因，不要自行扩大实现范围。若同一个「需要对齐」阻断没有任何新信息，不要重复修改代码或重新尝试同一方案，只需简洁重申阻断状态。

约定不变：不要 commit 或 push，修复后运行相关检查并如实报告结果。最后按同样格式输出本轮交付摘要。
`,
    }),
    agent({
      id: "acceptance",
      label: "验收 Reviewer",
      session: { mode: "inherit", key: "acceptance_room" },
      prompt: `
启动工作目录：
{{workflow.cwd}}

原始需求：
{{requirement}}

你是独立验收 Reviewer，不需要也不允许修改代码。你不会收到 RD 的交付摘要、改动范围或技术解释；不要猜测 RD 的意图，也不要依赖其自述。请只依据原始需求和仓库当前实际状态，独立判断当前实现与技术方案是否满足要求。

验收方法：
1. 先从原始需求提炼逐条、可验证的验收标准；不得自行增加产品需求或扩大范围。
2. 独立查看 git status、git diff、相关代码、测试和配置，理解仓库当前实现及其方案。实际代码是唯一实现证据。
3. 按验收标准逐项验证当前行为，运行与本次需求相关的 focused checks；无法验证的项目必须明确说明原因。
4. 检查实现是否完整覆盖相关调用面、是否引入明显回归，以及必要测试是否缺失。

判定标准：
- FAIL 仅用于不满足原始需求的阻断性问题；风格、可读性等改进意见标注为"建议"，不作为 FAIL 依据。
- FAIL 时反馈必须逐条列出：位置（文件/函数）、问题、证据、期望行为，并标注"阻断"或"建议"。
- 如果原始需求缺少作出判断所必需的信息，不要替用户做产品决策；把缺口列为"阻断：需要对齐"并返回 FAIL。

输出顺序：验收标准及结论、阻断问题、建议、已运行检查及结果、未验证项。没有内容的章节写"无"。最后一个非空行必须只返回以下两种状态之一：
PASS
FAIL
`,
      appendPrompt: `
第 {{iteration}} 轮验收。

请继续只依据原始需求和仓库当前实际状态重新验收。独立查看当前代码与 diff，逐条核对你上一轮标注为"阻断"的问题是否已解决，同时检查当前实现是否引入新问题。不要向 RD 索取或推断交付摘要。若原始需求、相关代码和同一个「需要对齐」阻断都没有变化，不要重复运行无关检查或扩写相同意见；简洁确认阻断仍存在并返回 FAIL。判定标准与输出格式不变。

最后一个非空行必须只返回以下两种状态之一：
PASS
FAIL
`,
    }),
  ],
  until: { source: "acceptance", finalStatus: "PASS" },
});

phase("提交");

agent({
  id: "submit_mr",
  label: "提交 MR",
  cwd: ".",
  inputs: { delivery_loop },
  prompt: `
启动工作目录：
{{workflow.cwd}}

原始需求：
{{requirement}}

交付循环结果：
{{delivery_loop}}

只把交付循环结果用于判断验收门禁：开头的 Stop reason 为 until_matched 表示验收 PASS；为 max_iterations_reached 表示打满轮次仍未通过。不要依赖其中的 RD 交付摘要来推断 PR 范围或内容。

若验收未通过：不要创建 MR/PR，也不要 commit。直接检查当前仓库状态并输出现状报告：
- 当前已完成的工作与改动文件
- 未通过的验收问题（从 [acceptance] 输出逐条整理）
- 建议的下一步

若验收已通过，请以当前工作区和原始需求为准提交 MR/PR，不需要重建或推断流程开始前的基线：
1. 检查当前分支、git status 和 git diff，独立总结当前改动形成的实际实现方案，并据此确定提交内容和 PR 说明。
2. 如当前分支不适合直接提交，创建语义清晰的新分支。
3. 提交前根据项目实际情况运行必要的 focused checks；无法运行时说明原因。
4. 使用准确、简洁的 commit message 提交当前交付，push 分支并使用仓库可用工具创建 MR/PR。
5. PR 标题和正文只描述原始需求、当前实际改动、技术方案和验证结果，不复述 RD/Reviewer 的过程性对话。
6. 如果缺少 remote、认证、权限或 MR/PR 工具不可用，不要伪造链接；报告阻塞点，并输出已准备好的分支、commit 和下一步命令。

最终只输出：
- 结果：MR/PR 链接 / 阻塞原因 / 未通过现状报告
- 分支名与 commit id（如有）
- 已运行的检查
- 本次提交或现状摘要
`,
});
